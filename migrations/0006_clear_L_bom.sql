-- 清空 L(大杯) 规格的配方数据。
--
-- 【原因】L 规格的 BOM 是项目早期随机生成的演示种子数据，物料与用量均为乱配，例如：
--   燕麦拿铁 hot|L = M3瑰夏咖啡豆 325g + 纯牛奶 1.3ml  -> 单杯成本 ¥75.90（荒谬）
--   燕麦拿铁 hot|M = OT燕麦奶 250ml                    -> 单杯成本 ¥3.28（真实配方）
-- 历史 211 笔销售中有 110 笔 size=L，套用该假配方会把毛利全部吃掉（毛利率算出 0.9%）。
--
-- 【处理】删除所有 L 规格配方行，保留 L 作为未来真上大杯时的预留位（届时在
-- 「商品与配方」编辑器放开 L 选项录入即可，BOM 结构无需改动）。
-- 前端对 size=L 的历史销售统一回退用 M 配方核算成本。
--
-- 【影响范围】仅 boms 表中 pk 以 '|L' 结尾的行；M 规格配方、加料配方(a|xxx)、
-- 销售记录、库存、单据均不受影响。

DELETE FROM boms WHERE pk LIKE '%|L';
